#include "textflag.h"

// func DumpXMM(buf *[256]byte)
TEXT ·DumpXMM(SB), NOSPLIT, $0-8
	MOVQ  buf+0(FP), AX
	MOVOU X0, 0(AX)
	MOVOU X1, 16(AX)
	MOVOU X2, 32(AX)
	MOVOU X3, 48(AX)
	MOVOU X4, 64(AX)
	MOVOU X5, 80(AX)
	MOVOU X6, 96(AX)
	MOVOU X7, 112(AX)
	MOVOU X8, 128(AX)
	MOVOU X9, 144(AX)
	MOVOU X10, 160(AX)
	MOVOU X11, 176(AX)
	MOVOU X12, 192(AX)
	MOVOU X13, 208(AX)
	MOVOU X14, 224(AX)
	MOVOU X15, 240(AX)
	RET

// func FillXMM(buf *[256]byte)
// X15 deliberately not loaded: it is the ABI's fixed zero (see probe_amd64.go).
TEXT ·FillXMM(SB), NOSPLIT, $0-8
	MOVQ  buf+0(FP), AX
	MOVOU 0(AX), X0
	MOVOU 16(AX), X1
	MOVOU 32(AX), X2
	MOVOU 48(AX), X3
	MOVOU 64(AX), X4
	MOVOU 80(AX), X5
	MOVOU 96(AX), X6
	MOVOU 112(AX), X7
	MOVOU 128(AX), X8
	MOVOU 144(AX), X9
	MOVOU 160(AX), X10
	MOVOU 176(AX), X11
	MOVOU 192(AX), X12
	MOVOU 208(AX), X13
	MOVOU 224(AX), X14
	RET

// func DumpZMMHi(buf *[1024]byte)
// Requires: AVX-512F.
